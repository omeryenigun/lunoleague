List<WordEntity> buildSeedWordsEn({DateTime? now}) {
  final t = now ?? DateTime.now();
  final locale = GameLocale.en;
  final out = <WordEntity>[];
  for (var i = 0; i < _seed.length; i++) {
    final p = _seed[i].split('|');
    final word = p[0];
    final length = locale.letterCount(word);
    if (length < 5 || length > 7) continue;
    out.add(
      WordEntity(
        id: 'word_en_${(i + 1).toString().padLeft(3, '0')}',
        word: word,
        language: 'en',
        length: length,
        difficulty: int.parse(p[1]),
        frequency: int.parse(p[2]),
        category: p[3],
        definition: p[4],
        exampleSentence: p[5],
        englishTranslation: word,
        status: WordStatus.active,
        isActive: true,
        usedCount: 0,
        createdAt: t,
        updatedAt: t,
      ),
    );
  }
  return out;
}
