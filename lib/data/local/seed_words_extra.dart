List<WordEntity> buildExtraLocaleWords({DateTime? now}) {
  final t = now ?? DateTime.now();
  final out = <WordEntity>[];
  final counts = <String, int>{};
  for (final row in _rows) {
    final parts = row.split('|');
    final language = parts[0];
    final locale = GameLocale.resolve(language);
    final word = locale.writtenUpper(parts[1]);
    final length = locale.letterCount(word);
    if (length < 5 || length > 7 || !locale.isAllowedWord(word)) continue;
    final n = (counts[language] ?? 0) + 1;
    counts[language] = n;
    out.add(
      WordEntity(
        id: 'word_${language}_${n.toString().padLeft(3, '0')}',
        word: word,
        language: language,
        length: length,
        difficulty: 2,
        frequency: 4,
        category: parts[2],
        definition: parts[3],
        exampleSentence: '',
        englishTranslation: '',
        status: WordStatus.active,
        isActive: true,
        usedCount: 0,
        createdAt: t,
        updatedAt: t,
      ),
    );
  }
  return out;
}
