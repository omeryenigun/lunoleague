function currentLang() {
  const saved = localStorage.getItem('ony-lang');
  return saved === 'en' ? 'en' : 'tr';
}

function t(key) {
  return (I18N[currentLang()] || I18N.tr)[key] || key;
}

function applyI18n() {
  const lang = currentLang();
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = t(el.dataset.i18n);
    if (el.dataset.i18nHtml === '1') el.innerHTML = value;
    else el.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('.langs button').forEach((btn) => {
    btn.setAttribute('aria-pressed', btn.dataset.lang === lang ? 'true' : 'false');
  });
  const titleKey = document.body.dataset.title;
  if (titleKey) document.title = `${t(titleKey)} — Onyapp`;
}

function setLang(lang) {
  localStorage.setItem('ony-lang', lang === 'en' ? 'en' : 'tr');
  applyI18n();
  document.dispatchEvent(new Event('ony-lang'));
}
